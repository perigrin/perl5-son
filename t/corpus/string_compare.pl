# StrCmp, StrGe, StrGt, StrLe, StrLt, StrEq, StrNe
my $a = "apple";
my $b = "banana";
print $a cmp $b, "\n";
print(($a ge $b) ? 1 : 0, "\n");
print(($a gt $b) ? 1 : 0, "\n");
print(($a le $b) ? 1 : 0, "\n");
print(($a lt $b) ? 1 : 0, "\n");
print(($a eq $b) ? 1 : 0, "\n");
print(($a ne $b) ? 1 : 0, "\n");
